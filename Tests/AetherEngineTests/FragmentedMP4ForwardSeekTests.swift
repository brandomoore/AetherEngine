                landing = Double(packet.pointee.pts) * Double(tb.num) / Double(tb.den)
            }
            var owned: UnsafeMutablePointer<AVPacket>? = packet
            trackedPacketFree(&owned)
        }
        let seconds = try #require(landing)
        #expect(seconds >= 6.0 && seconds <= 8.0, "landed at \(seconds) s")
    }

